// User table with auth and role support
export const user = pgTable('user', {
	id: text('id').primaryKey(), // UUID generated by Lucia or your auth flow

	email: text('email').notNull().unique(),
	hashedPassword: text('hashed_password').notNull(), // hashed_password is the DB column, but use camelCase in code

	// User profile
	firstName: text('first_name').notNull(),
	lastName: text('last_name').notNull(),
	gemId: text('gem_id'), // Optional GEM ID for tournament registration

	// Billing tier — the paywall gate. Exactly one value per user.
	role: text('role').notNull().default('free'), // 'free' | 'premium' | 'admin'

	// Capability roles — stackable, independent of billing tier. A user
	// can hold any combination of these AND their primary billing role.
	// Options: 'writer' (author library entries), 'creator' (author
	// courses), 'tournament staff' (event operations). Empty array = no
	// capability roles. See src/lib/server/auth/roles.js for guards.
	additionalRoles: text('additional_roles')
		.array()
		.notNull()
		.default(sql`ARRAY[]::text[]`),

	// Authorize.net Customer Profile (for saved cards)
	customerProfileId: text('customer_profile_id'), // Authorize.net CIM customer profile ID

	// Subscription tracking
	subscriptionId: text('subscription_id'), // Authorize.net subscription ID for premium users
	subscriptionType: text('subscription_type'), // 'monthly' or 'yearly'
	subscriptionStatus: text('subscription_status'), // 'active', 'cancelled', 'expired'
	subscriptionStartDate: timestamp('subscription_start_date', { withTimezone: true, mode: 'date' }),
	subscriptionEndDate: timestamp('subscription_end_date', { withTimezone: true, mode: 'date' }), // When access expires (for cancelled subs)
	nextBillingDate: timestamp('next_billing_date', { withTimezone: true, mode: 'date' }),

	// Partner program — tracks the partner code a user redeemed (one per user, ever)
	usedPartnerCode: text('used_partner_code'),

	// Comped premium (premium without a subscription): why, when and by
	// whom. Set by the admin role controls; see migration 022.
	compReason: text('comp_reason'), // 'staff' | 'writer' | 'teacher' | 'partner' | 'friend' | 'trial' | 'other'
	compedAt: timestamp('comped_at', { withTimezone: true, mode: 'date' }),
	compedBy: text('comped_by'),
	// Kept when subscription_id is cleared on expiry, so a lapsed
	// subscriber is still told apart from a comp.
	lastSubscriptionId: text('last_subscription_id'),

	createdAt: timestamp('created_at', {
		withTimezone: true,
		mode: 'date'
	}).defaultNow()
});

